"""Core data models for LogSentinel."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any


class Severity(str, Enum):
    """Alert and incident severity levels."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"

    @property
    def base_score(self) -> int:
        return {
            Severity.LOW: 20,
            Severity.MEDIUM: 45,
            Severity.HIGH: 72,
            Severity.CRITICAL: 92,
        }[self]

    @property
    def rank(self) -> int:
        return {
            Severity.LOW: 1,
            Severity.MEDIUM: 2,
            Severity.HIGH: 3,
            Severity.CRITICAL: 4,
        }[self]

    @classmethod
    def from_score(cls, score: int) -> "Severity":
        if score >= 85:
            return cls.CRITICAL
        if score >= 65:
            return cls.HIGH
        if score >= 35:
            return cls.MEDIUM
        return cls.LOW


@dataclass(slots=True)
class SecurityEvent:
    """Normalized security event parsed from heterogeneous log sources."""

    timestamp: datetime
    source_format: str
    event_type: str
    action: str
    outcome: str
    raw: str
    line_number: int
    source_ip: str | None = None
    username: str | None = None
    target: str | None = None
    user_agent: str | None = None
    status_code: int | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def get_field(self, name: str) -> Any:
        """Retrieve a normalized attribute or metadata field by name."""
        if hasattr(self, name):
            return getattr(self, name)
        return self.metadata.get(name)


@dataclass(slots=True)
class DetectionRule:
    """Sigma-inspired detection rule supporting match, threshold, and sequence logic."""

    id: str
    title: str
    description: str
    severity: Severity
    mitre_tactic: str
    mitre_technique: str
    rule_type: str  # "match" | "threshold" | "sequence"
    formats: list[str]
    match: dict[str, Any] = field(default_factory=dict)
    group_by: str = "source_ip"
    threshold: int = 1
    window_seconds: int = 60
    first_match: dict[str, Any] = field(default_factory=dict)
    then_match: dict[str, Any] = field(default_factory=dict)
    min_first_count: int = 3
    tags: list[str] = field(default_factory=list)
    remediation: str = ""


@dataclass(slots=True)
class Alert:
    """Individual detection alert generated by a rule."""

    alert_id: str
    rule_id: str
    rule_title: str
    severity: Severity
    mitre_tactic: str
    mitre_technique: str
    timestamp: datetime
    description: str
    risk_score: int
    source_ip: str | None = None
    username: str | None = None
    evidence_count: int = 1
    sample_raw: list[str] = field(default_factory=list)
    ioc_matches: list[str] = field(default_factory=list)
    remediation: str = ""


@dataclass(slots=True)
class Incident:
    """Grouped, prioritized SOC incident aggregated from related alerts."""

    incident_id: str
    title: str
    severity: Severity
    risk_score: int
    first_seen: datetime
    last_seen: datetime
    source_ip: str | None = None
    usernames: list[str] = field(default_factory=list)
    mitre_techniques: list[str] = field(default_factory=list)
    alerts: list[Alert] = field(default_factory=list)
    ioc_matches: list[str] = field(default_factory=list)
    recommended_actions: list[str] = field(default_factory=list)

    @property
    def alert_count(self) -> int:
        return len(self.alerts)


@dataclass(slots=True)
class AnalysisSummary:
    """Complete analysis output for a log triage run."""

    source_file: str
    detected_format: str
    total_lines: int
    parsed_events: int
    skipped_lines: int
    rules_loaded: int
    alerts: list[Alert]
    incidents: list[Incident]
    generated_at: datetime
    duration_ms: float
